import Foundation
import ClipCopyCore

@MainActor final class ClipCopyCoreTests: LocalTestCase {
    func testEntryDefaultsAndWhitespaceRules() {
        let now = Date(timeIntervalSince1970: 100)
        let entry = ClipEntry(text: "  hello\n")
        expectEqual(entry.text, "  hello\n")
        expectEqual(entry.lastCapturedAt, entry.createdAt)
        expectEqual(ClipEntry(text: "\n\t ").text, "\n\t ")
        var history = History()
        expectFalse(history.ingest(ClipEntry(text: "   ")))
        expectTrue(history.ingest(ClipEntry(text: "  hello\n", createdAt: now)))
    }

    func testIngestDeduplicatesUTF8AndKeepsNewestAtFront() {
        let first = ClipEntry(text: "same", createdAt: Date(timeIntervalSince1970: 1))
        let duplicate = ClipEntry(text: "same", createdAt: Date(timeIntervalSince1970: 2))
        var history = History(entries: [first])
        expectFalse(history.ingest(duplicate))
        expectEqual(history.entries.count, 1)
        expectEqual(history.entries[0].id, first.id)
        expectTrue(history.ingest(ClipEntry(text: "other")))
        expectEqual(history.entries.map(\.text), ["other", "same"])
    }

    func testImportKeepsDuplicatesButCapsStoreLimitAndOldest() {
        let entries = (0..<1001).map { ClipEntry(text: "item-\($0)") }
        let history = History(entries: entries, settings: ClipSettings(storeLimit: 1000, displayLimit: 1000))
        expectEqual(history.entries.count, 1000)
        expectEqual(history.entries.first?.text, "item-0")
        expectFalse(history.entries.contains { $0.text == "item-1000" })
        let duplicateHistory = History(entries: [ClipEntry(text: "x"), ClipEntry(text: "x")])
        expectEqual(duplicateHistory.entries.count, 2)
    }

    func testVisibleEntriesPrefixAndSearch() {
        let entries = [ClipEntry(text: "Alpha"), ClipEntry(text: "Äpfel"), ClipEntry(text: "beta"), ClipEntry(text: "alphabet")]
        let history = History(entries: entries, settings: ClipSettings(storeLimit: 10, displayLimit: 2))
        expectEqual(history.visibleEntries(query: "").map(\.text), ["Alpha", "Äpfel"])
        expectEqual(history.visibleEntries(query: "ALPHA").map(\.text), ["Alpha", "alphabet"])
        expectEqual(history.visibleEntries(query: "apfel").map(\.text), ["Äpfel"])
    }

    func testSettingsValidationAndUpdateLimit() throws {
        expectThrows(try ClipSettings(storeLimit: 0).validated())
        expectThrows(try ClipSettings(storeLimit: 1, displayLimit: 2).validated())
        var history = History(entries: (0..<4).map { ClipEntry(text: "\($0)") }, settings: ClipSettings(storeLimit: 4, displayLimit: 4))
        expectThrows(try history.updateSettings(ClipSettings(storeLimit: 0)))
        try history.updateSettings(ClipSettings(storeLimit: 2, displayLimit: 1))
        expectEqual(history.entries.count, 2)
        expectEqual(history.entries.map(\.text), ["0", "1"])
    }

    func testMutationsAndLookup() {
        let id = UUID()
        var history = History(entries: [ClipEntry(id: id, text: "x"), ClipEntry(text: "y")])
        expectEqual(history.entry(id: id)?.text, "x")
        history.remove(id: id)
        expectNil(history.entry(id: id))
        history.removeAll()
        expectTrue(history.entries.isEmpty)
    }

    func testCapturePolicyRejectsWithoutCallingReader() {
        let policy = CapturePolicy()
        let forbidden = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type", "com.typeit4me.clipping", "com.mediapublishing.ClipCopy.owned"]
        for type in forbidden {
            var calls = 0
            let result = policy.readAllowedText(types: [type, "public.utf8-plain-text"], sourceBundleID: "com.example.App", activeBundleID: "com.example.App", activeAppName: "Example", numberOfItems: 1, paused: false, locked: false) { calls += 1; return "secret" }
            expectNil(result, type)
            expectEqual(calls, 0, type)
        }
    }

    func testRichTextWithExplicitPlainRepresentationIsAccepted() {
        expectEqual(CapturePolicy().readAllowedText(types: ["public.html", "public.utf8-plain-text"], sourceBundleID: nil, activeBundleID: "com.example.editor", activeAppName: "Editor", numberOfItems: 1, paused: false, locked: false) { "Web text" }, "Web text")
    }

    func testCapturePolicyRequiresExactlyOnePlainTextAndKnownForeground() {
        let policy = CapturePolicy(excludedBundleIDs: ["com.blocked.app"], excludedNames: ["Password Manager"])
        var calls = 0
        func read() -> String? { calls += 1; return "ok" }
        expectNil(policy.readAllowedText(types: ["public.utf8-plain-text"], sourceBundleID: nil, activeBundleID: nil, activeAppName: nil, numberOfItems: 1, paused: false, locked: false, readText: read))
        expectNil(policy.readAllowedText(types: ["public.html"], sourceBundleID: "com.example", activeBundleID: "com.example", activeAppName: "Example", numberOfItems: 1, paused: false, locked: false, readText: read))
        expectNil(policy.readAllowedText(types: ["public.utf8-plain-text"], sourceBundleID: "com.blocked.app", activeBundleID: "com.example", activeAppName: "Example", numberOfItems: 1, paused: false, locked: false, readText: read))
        expectNil(policy.readAllowedText(types: ["public.utf8-plain-text"], sourceBundleID: "com.example", activeBundleID: "com.example", activeAppName: "password manager", numberOfItems: 1, paused: false, locked: false, readText: read))
        expectEqual(policy.readAllowedText(types: ["public.plain-text"], sourceBundleID: "com.example", activeBundleID: "com.example", activeAppName: "Example", numberOfItems: 1, paused: false, locked: false, readText: read), "ok")
        expectEqual(calls, 1)
    }

    func testCapturePolicyRejectsPausedLockedOrWrongCount() {
        let policy = CapturePolicy()
        for state in [(true, false, 1), (false, true, 1), (false, false, 0), (false, false, 2)] {
            var calls = 0
            expectNil(policy.readAllowedText(types: ["public.utf8-plain-text"], sourceBundleID: "com.example", activeBundleID: "com.example", activeAppName: "Example", numberOfItems: state.2, paused: state.0, locked: state.1) { calls += 1; return "x" })
            expectEqual(calls, 0)
        }
    }
}
