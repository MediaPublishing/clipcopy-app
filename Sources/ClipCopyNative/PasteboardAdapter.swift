import AppKit
import ClipCopyCore

@MainActor public final class PasteboardAdapter {
    private let board: NSPasteboard
    public var changeCount: Int { board.changeCount }
    public init(board: NSPasteboard) { self.board = board }
    public var capturePermitted: Bool {
        if #available(macOS 15.4, *) { return board.accessBehavior == .alwaysAllow }
        return false
    }
    public func capture(policy: CapturePolicy, activeID: String?, activeName: String?, paused: Bool, locked: Bool,
                        stillValid: () -> Bool) -> String? {
        guard !paused, !locked, capturePermitted else { return nil }
        let generation = board.changeCount
        guard let items = board.pasteboardItems, items.count == 1, let item = items.first else { return nil }
        let types = Set(item.types.map(\.rawValue))
        // Sensitive metadata is checked before reading even the optional source marker.
        guard types.isDisjoint(with: CapturePolicy.forbiddenTypes) else { return nil }
        let source = item.string(forType: .init("org.nspasteboard.source"))
        let plainTypes: [NSPasteboard.PasteboardType] = [.string, .init("public.plain-text"), .init("NSStringPboardType")]
        guard let plainType = plainTypes.first(where: { item.types.contains($0) }) else { return nil }
        let text = policy.readAllowedText(types: types, sourceBundleID: source, activeBundleID: activeID,
                                           activeAppName: activeName, numberOfItems: items.count, paused: paused, locked: locked) {
            item.string(forType: plainType)
        }
        guard generation == board.changeCount, stillValid() else { return nil }
        return text
    }
    public func write(_ text: String) -> Bool {
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string),
              item.setData(Data(), forType: .init(CapturePolicy.ownedType)),
              item.setData(Data(), forType: .init("org.nspasteboard.AutoGeneratedType")) else { return false }
        board.prepareForNewContents(with: .currentHostOnly)
        return board.writeObjects([item])
    }
}
